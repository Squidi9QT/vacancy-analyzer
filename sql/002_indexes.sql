-- q5 «новые за 7 дней»: фильтр first_seen_at >= <неделю назад> отбирает ~3 % строк.
-- Без индекса PostgreSQL читает все 300 тыс. вакансий, чтобы найти 9 тыс.
CREATE INDEX IF NOT EXISTS idx_vacancy_first_seen_at ON vacancy (first_seen_at);

-- q5, поиск возможного дубля: тот же работодатель + город + название без учёта регистра
-- + создан за 14 дней до. Подзапрос выполняется для КАЖДОЙ новой вакансии (тысячи раз).
-- Без индекса каждый раз склеиваются два индекса (employer_id и area_id) — BitmapAnd.
-- Составной индекс отвечает одним спуском по дереву.
-- lower(name) — индекс по ВЫРАЖЕНИЮ: он сработает, только если в запросе написано
-- ровно lower(name). Индекс по name для условия lower(d.name) = … бесполезен.
-- Порядок колонок: сначала условия на равенство, последней — колонка диапазона
-- (created_at): по ней B-tree отбирает непрерывный кусок.
CREATE INDEX IF NOT EXISTS idx_vacancy_duplicate_lookup
    ON vacancy (employer_id, area_id, lower(name), created_at);
